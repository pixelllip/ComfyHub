package com.comfyhub

import kotlinx.serialization.json.JsonArray
import kotlinx.serialization.json.JsonElement
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.JsonPrimitive
import kotlinx.serialization.json.buildJsonArray
import kotlinx.serialization.json.buildJsonObject
import kotlinx.serialization.json.contentOrNull
import kotlinx.serialization.json.put
import org.slf4j.LoggerFactory
import java.nio.file.Files
import java.nio.file.Path
import java.nio.file.Paths

/**
 * 「这台机器上的 ComfyUI 到底是怎么配的」—— 从 **ComfyUI Desktop 自己的配置**里**只读**地读出来。
 *
 * ## 为什么需要它（2026-09-22 现场）
 *
 * 会话 `0bedb3f5`（「启动 ComfyUI」）里 AI 花了 30 分钟、来回十几轮，最后得出
 * "本机没有 `anima-base-v1.0` / `qwen_3_06b_base` / 加速 LoRA" —— **一半是错的**：
 * 那些文件就躺在 `D:\Comfy-Desktop\ComfyUI-Shared\models` 里。
 *
 * 根因不是"AI 没看"，而是**两个模型根**：
 *
 *  - 用户日常跑的是 **ComfyUI Desktop**，它的模型/输入/输出都在共享目录
 *    （`settings.json` 里 `modelsDirs` / `inputDir` / `outputDir`）；
 *  - 而 `launch_comfyui`（comfy-mcp → `comfy launch --background`）是**直接跑 `main.py`**，
 *    Desktop 那套配置一个都没传 —— 安装根里只有 `extra_model_paths.yaml.example`，
 *    所以这个实例的 `models\` 是另一套（`diffusion_models\` 只有 2 个 minimax），
 *    `input` 是它自己的 input（于是 `comfy_use_attachment` 投到 Shared\input 的图它找不到），
 *    `output` 也是它自己的 output（于是**我方自动捕获盯的 Shared\output 收不到 AI 自己跑出来的图**）。
 *
 * 用户 2026-09-22 拍板："**以防万一还是把 shared 默认挂上**"。
 * 所以这里的职责是：把 Desktop 的配置算成 `launch_comfyui` 应该补的三个参数，
 * 由 [com.comfyhub.ai.mcp.McpToolBridge] 在模型调 `launch_comfyui` 时**自动补上**
 * （模型不需要知道这件事，也不该由它决定）。
 *
 * ## 四条纪律
 *
 *  1. **只读，一个字节都不写**：Desktop 的 `settings.json` / `shared_model_paths.yaml`
 *     都带着 "Generated by Comfy Desktop — do not edit manually"，我们只读不算改。
 *  2. **拿不到就如实说**：没有 Desktop 配置时**不编**参数，而是给模型一段警告
 *     （"这次启动的实例看不到共享模型，别据此断言本机没有某个模型"）——
 *     这比"看起来一切正常"有用得多。
 *  3 . **不覆盖模型自己写的参数**：模型显式写了 `--extra-model-paths-config` / `--input-directory` /
 *     `--base-directory` 时一律尊重，只在结果里说清"我没有覆盖它"。
 *  4. **参数只在目录真的存在时才加** —— 给 ComfyUI 一个不存在的 input/output 目录，
 *     启动会直接失败，那比不挂更糟。
 */
object ComfyEnv {

    private val log = LoggerFactory.getLogger(ComfyEnv::class.java)

    /** ComfyUI Desktop 在 `%APPDATA%` 下的配置目录名（实测本机就长这样）。 */
    const val DESKTOP_DIR = "Comfy Desktop"

    private const val SETTINGS = "settings.json"
    private const val SHARED_YAML = "shared_model_paths.yaml"
    private const val INSTANCE_YAML_DIR = "instance-model-paths"

    /** 我们会补的三个参数（判重就按它们）。 */
    const val FLAG_MODEL_PATHS = "--extra-model-paths-config"
    const val FLAG_INPUT = "--input-directory"
    const val FLAG_OUTPUT = "--output-directory"

    /** 模型自己写这个时，input/output 由它说了算，我们不再插嘴。 */
    private const val FLAG_BASE = "--base-directory"

    /**
     * 一台机器上读到的 Desktop 配置（全是事实，读取失败就是 null / 空列表）。
     */
    data class Desktop(
        val desktopDir: Path,
        val settingsFile: Path? = null,
        /** Desktop 生成的模型路径映射文件（`--extra-model-paths-config` 的值）。 */
        val modelPathsConfig: Path? = null,
        /** 用户的所有模型根（本机实测有两个：`…\ComfyUI-Shared\models` 与 `E:\ComfyUI\models`）。 */
        val modelsDirs: List<Path> = emptyList(),
        val inputDir: Path? = null,
        val outputDir: Path? = null,
        val installDir: Path? = null,
        /** 给用户/模型看的一句话出处。 */
        val source: String = "ComfyUI Desktop 的配置",
    )

    /** `%APPDATA%\Comfy Desktop`（拿不到 APPDATA 就 null）。 */
    fun defaultDesktopDir(): Path? {
        val appData = System.getenv("APPDATA")?.takeIf { it.isNotBlank() } ?: return null
        return runCatching { Paths.get(appData).resolve(DESKTOP_DIR) }.getOrNull()
    }

    /**
     * 读 Desktop 的配置。
     *
     * @param dir 配置目录；默认 `%APPDATA%\Comfy Desktop`（测试里换成临时目录）。
     * @return 两边配置都没有时返回 null（= 这台机器没装 ComfyUI Desktop，属正常情形）。
     */
    fun desktop(dir: Path? = defaultDesktopDir()): Desktop? {
        if (dir == null || !Files.isDirectory(dir)) return null
        val settingsFile = dir.resolve(SETTINGS).takeIf { Files.isRegularFile(it) }
        val shared = dir.resolve(SHARED_YAML).takeIf { Files.isRegularFile(it) }
        val instance = firstYaml(dir.resolve(INSTANCE_YAML_DIR))
        val paths = shared ?: instance
        val obj = settingsFile?.let { readObject(it) }
        if (obj == null && paths == null) return null

        val models = obj?.get("modelsDirs").asPathList()
        val input = obj?.get("inputDir").asExistingDir()
        val output = obj?.get("outputDir").asExistingDir()
        val install = obj?.get("installDir").asExistingDir()

        val source = when {
            settingsFile != null && paths != null ->
                "ComfyUI Desktop 的 settings.json 与 ${paths.fileName}"
            settingsFile != null -> "ComfyUI Desktop 的 settings.json"
            else -> "ComfyUI Desktop 的 ${paths?.fileName}"
        }
        return Desktop(
            desktopDir = dir,
            settingsFile = settingsFile,
            modelPathsConfig = paths,
            modelsDirs = models,
            inputDir = input,
            outputDir = output,
            installDir = install,
            source = source,
        )
    }

    /** 一次参数注入的结果：改过的参数 + 要**如实回给模型**的一段说明（没有就是 null）。 */
    data class LaunchPlan(val args: JsonObject, val note: String?)

    /**
     * 给 `launch_comfyui` 的参数做"补挂共享模型根"。
     *
     * 纯函数（除了读一次磁盘上的 Desktop 配置）——不改用户的任何文件，
     * 只是把 `extra_args` 补齐：`--extra-model-paths-config` + `--input-directory` + `--output-directory`。
     * 模型自己写过的参数一律不重复、不覆盖（[Desktop] 的说明里会写清我们没动它）。
     */
    fun prepareLaunch(args: JsonObject, desktop: Desktop? = desktop()): LaunchPlan {
        val existing = args["extra_args"].asArgv()
        val flags = existing.filter { it.startsWith("--") }.toSet()
        val out = existing.toMutableList()
        val added = mutableListOf<String>()
        val notes = mutableListOf<String>()

        if (desktop == null) {
            notes += "⚠ 没读到 ComfyUI Desktop 的配置（`%APPDATA%\\$DESKTOP_DIR\\settings.json`）。" +
                "如果用户的模型放在共享目录（例如 `…\\ComfyUI-Shared\\models`）或别的盘，" +
                "**这次启动的实例看不到它们**（`/object_info` 里不会出现）——" +
                "别据此断言\"本机没有某个模型\"，先用 `comfy_env_report` 对账。"
        } else {
            val cfg = desktop.modelPathsConfig
            when {
                FLAG_MODEL_PATHS in flags ->
                    notes += "模型根：**尊重模型自己写的** `$FLAG_MODEL_PATHS`，ComfyHub 没有覆盖。"
                cfg != null -> {
                    out += listOf(FLAG_MODEL_PATHS, cfg.toString())
                    added += FLAG_MODEL_PATHS
                }
                else -> notes += "⚠ ComfyUI Desktop 没有生成模型路径映射文件（`$SHARED_YAML` / " +
                    "`$INSTANCE_YAML_DIR\\*.yaml`），共享模型根这次挂不上。"
            }
            if (FLAG_BASE in flags) {
                notes += "模型自己写了 `$FLAG_BASE`，ComfyHub 不再补 input/output（免得跟它的意图打架）。"
            } else {
                if (FLAG_INPUT !in flags && desktop.inputDir != null) {
                    out += listOf(FLAG_INPUT, desktop.inputDir.toString())
                    added += FLAG_INPUT
                }
                if (FLAG_OUTPUT !in flags && desktop.outputDir != null) {
                    out += listOf(FLAG_OUTPUT, desktop.outputDir.toString())
                    added += FLAG_OUTPUT
                }
            }
        }

        val note = renderNote(desktop, added, notes)
        return LaunchPlan(withArgv(args, out), note)
    }

    // -----------------------------------------------------------------------
    //  内部
    // -----------------------------------------------------------------------

    /**
     * 把补好的 argv 写回参数对象。
     *
     * ⚠ 顺序上先擦掉旧的 `extra_args` 再写新的：模型经常把数组写成**一个 JSON 字符串**
     * （现场实测 `{"extra_args": "[\"--port\", \"8189\"]"}`，而 schema 声明的是数组），
     * 这里顺手把它归一成真正的数组 —— 那是它本来就该是的样子。
     */
    private fun withArgv(args: JsonObject, argv: List<String>): JsonObject = buildJsonObject {
        args.forEach { (k, v) -> if (k != "extra_args") put(k, v) }
        if (argv.isNotEmpty()) {
            put("extra_args", buildJsonArray { argv.forEach { add(JsonPrimitive(it)) } })
        }
    }

    private fun renderNote(
        desktop: Desktop?,
        added: List<String>,
        notes: List<String>,
    ): String? {
        if (desktop == null && notes.isEmpty()) return null
        val sb = StringBuilder()
        if (desktop != null) {
            sb.append("【ComfyHub 环境对账】这个实例是照 ComfyUI Desktop 的配置起的（来源：")
                .append(desktop.source).append("）\n")
            if (desktop.modelsDirs.isNotEmpty()) {
                sb.append("· 模型根：")
                    .append(desktop.modelsDirs.joinToString("、") { it.toString() })
                    .append('\n')
            }
            if (FLAG_MODEL_PATHS in added) {
                sb.append("· 已挂 `").append(FLAG_MODEL_PATHS).append(' ')
                    .append(desktop.modelPathsConfig).append("`\n")
            }
            if (FLAG_INPUT in added || FLAG_OUTPUT in added) {
                sb.append("· 已挂 ")
                val parts = mutableListOf<String>()
                if (FLAG_INPUT in added) parts += "input = ${desktop.inputDir}"
                if (FLAG_OUTPUT in added) parts += "output = ${desktop.outputDir}"
                sb.append(parts.joinToString("，")).append('\n')
            }
            if (added.isNotEmpty()) {
                sb.append("（这些参数是 **ComfyHub 补的**，不是模型写的。少了它们，这个实例看不到共享模型、")
                    .append("产物也不会落进自动捕获盯着的那个 output 目录。）")
            } else {
                sb.append("（这次没有额外补参数。）")
            }
        }
        notes.forEach { n ->
            if (sb.isNotEmpty()) sb.append('\n')
            sb.append(n)
        }
        return sb.toString().trim().ifBlank { null }
    }

    private fun readObject(file: Path): JsonObject? = runCatching {
        AppJson.parseToJsonElement(Files.readString(file)) as? JsonObject
    }.onFailure { log.warn("读 ComfyUI Desktop 配置失败（忽略）：{} —— {}", file, it.message) }
        .getOrNull()

    /** `modelsDirs` 那种字符串数组。 */
    private fun JsonElement?.asPathList(): List<Path> {
        val arr = this as? JsonArray ?: return emptyList()
        return arr.mapNotNull { (it as? JsonPrimitive)?.contentOrNull?.takeIf { s -> s.isNotBlank() } }
            .mapNotNull { runCatching { Paths.get(it) }.getOrNull() }
    }

    /** `inputDir` / `outputDir` 那种**必须真实存在**的目录（不存在就不给，免得启动失败）。 */
    private fun JsonElement?.asExistingDir(): Path? {
        val raw = (this as? JsonPrimitive)?.contentOrNull?.takeIf { it.isNotBlank() } ?: return null
        val p = runCatching { Paths.get(raw) }.getOrNull() ?: return null
        return if (Files.isDirectory(p)) p else null
    }

    private fun firstYaml(dir: Path): Path? {
        if (!Files.isDirectory(dir)) return null
        return runCatching {
            Files.list(dir).use { stream ->
                stream.filter { Files.isRegularFile(it) }
                    .filter { it.fileName.toString().lowercase().endsWith(".yaml") }
                    .sorted()
                    .findFirst()
                    .orElse(null)
            }
        }.getOrNull()
    }

    /**
     * 把模型给的 `extra_args` 解析成 argv。
     *
     * 三种形状都认：数组（schema 声明的）、**JSON 字符串**（模型实际常写的）、
     * 以及最朴素的空格分隔字符串。认不出来的部分丢掉，绝不把半截参数塞给 ComfyUI。
     */
    internal fun JsonElement?.asArgv(): List<String> {
        val raw = when (this) {
            null -> emptyList()
            is JsonArray -> mapNotNull { (it as? JsonPrimitive)?.contentOrNull }
            is JsonPrimitive -> {
                // 数组解得出就用数组，解不出就按空白拆（`--port 8189` 这种最朴素的写法）
                val text = contentOrNull?.trim().orEmpty()
                if (text.isEmpty()) {
                    emptyList()
                } else {
                    runCatching {
                        (AppJson.parseToJsonElement(text) as? JsonArray)
                            ?.mapNotNull { (it as? JsonPrimitive)?.contentOrNull }
                    }.getOrNull() ?: text.split(' ').filter { it.isNotBlank() }
                }
            }
            else -> emptyList()
        }
        return raw.map { it.trim() }.filter { it.isNotEmpty() }
    }
}
